"""R11.27: compare report buttons without UI table; responsive Qt on all tabs.

No STEP/ABSR exporter or mass calculation changes. Big comparison result tables
are kept in HTML/CSV reports and no longer generated in the Qt widget.
"""
import os,json
from pathlib import Path
root=Path(os.environ['DS_COMPARE_SOURCE'])
p=root/'dsac29/gui_modern.py'
s=p.read_text('utf8')
def replace(a,b):
 global s
 n=s.count(a)
 if n!=1:raise RuntimeError(f'R11.27 Qt anchor occurred {n} times: {a[:100]!r}')
 s=s.replace(a,b,1)

# The Qt details frame exists only for old integrations. Do not insert it into
# the layout and never show it after computation.
replace("  lay.addWidget(self._details,1);self._details.hide();lay.addStretch(1)",
        "  self._details.hide();lay.addStretch(1)")
replace("   self._details.show()","   self._details.hide()")

# Prevent the lower comparison page from clipping when switching from a short
# window to the much taller mass page. Both pages now have independent vertical
# scroll areas; horizontal scrollbars never steal viewport space.
replace("  self._center_form_fields()\n",
        "  self._center_form_fields()\n  self._scroll_page('compare')\n  self._init_adaptive_window()\n")
anchor=" def _new_page(self"
at=s.find(anchor)
if at<0:raise RuntimeError('Missing class method _new_page for inserting responsive helpers')
helpers=""" def _init_adaptive_window(self):
  from PySide6.QtGui import QGuiApplication
  screen=self.screen() or QGuiApplication.primaryScreen()
  if screen is None:
   self.setMinimumSize(740,520);self.resize(1120,730);return
  area=screen.availableGeometry()
  # Work with Qt's logical pixels (also on Windows display scaling).
  min_w=min(760,max(560,area.width()-64))
  min_h=min(540,max(420,area.height()-64))
  self.setMinimumSize(min_w,min_h)
  width=max(min_w,min(1240,int(area.width()*.89)))
  height=max(min_h,min(870,int(area.height()*.87)))
  self.resize(width,height)
  rect=self.frameGeometry()
  rect.moveCenter(area.center())
  self.move(rect.topLeft())

"""
s=s[:at]+helpers+s[at:]

# Four mass action buttons in one rigid row were clipped at narrow widths.
# Two adaptive columns with two rows retain all four labels and controls.
a=s.index('  row=QHBoxLayout();row.setSpacing(9);row.addStretch()',s.index(' def _modern_mass(self):'))
b=s.index('  lay.addLayout(row)',a)+len('  lay.addLayout(row)')
old=s[a:b]
if "self.mass_remove_selected" not in old or "self.mass_reset" not in old:
 raise RuntimeError("Mass action region does not contain expected controls")
replacement="""  row=QGridLayout();row.setSpacing(9)
  self.run_mass.setText('Oblicz masę');self.run_mass.setMinimumWidth(155)
  self.mass_reset=QPushButton('Resetuj dane')
  self.mass_reset.setToolTip('Czyści listę modeli i bieżący wynik, nie usuwa plików.')
  self.mass_reset.clicked.connect(self._mass_reset)
  self.mass_remove_selected=QPushButton('Usuń zaznaczone')
  self.mass_remove_selected.setToolTip('Usuwa wskazane modele tylko z kolejki; nie usuwa plików z dysku.')
  self.mass_remove_selected.setEnabled(False)
  self.mass_remove_selected.clicked.connect(self._mass_remove_selected)
  row.addWidget(self.run_mass,0,0)
  row.addWidget(self.cancel_mass,0,1)
  row.addWidget(self.mass_remove_selected,1,0)
  row.addWidget(self.mass_reset,1,1)
  row.setColumnStretch(0,1);row.setColumnStretch(1,1)
  lay.addLayout(row)"""
s=s[:a]+replacement+s[b:]
p.write_text(s,encoding='utf8')

# Avoid reading potentially huge CSV and populating a table nobody can see.
# Existing HTML and CSV files are still generated by the report engine.
p=root/'dsac29/gui45.py'
s=p.read_text('utf8')
key="""            with (folder/'ZMIANY.csv').open(encoding='utf-8-sig',newline='') as f:rows=list(csv.reader(f,delimiter=';'))[1:]
"""
assert s.count(key)==1,s.count(key)
s=s.replace(key,"",1)
start=s.index("            self.compare_table.setRowCount(len(rows))")
end=s.index("            self.legend.setText(",start)
chunk=s[start:end]
assert 'self.filter_results();buttons=self.compare_open' in chunk
s=s[:start]+"""            # Results remain available in RAPORT.html and ZMIANY.csv.
            # Avoid extra Qt allocations for thousands of invisible rows.
            self.compare_table.setRowCount(0)
            self.row_statuses=[]
            buttons=self.compare_open
"""+s[end:]
p.write_text(s,encoding='utf8')

(root/'VERSION.txt').write_text('R11.27\n',encoding='utf8')
meta=root/'build_info.json'
if meta.is_file():
 obj=json.loads(meta.read_text('utf8'))
 obj['version']='R11.27 · GitHub '+os.environ.get('GITHUB_SHA','')[:8]
 obj['ui']='Comparison table removed, report links retained; auto-fit to screen and scrollable comparison, mass buttons in 2 rows'
 meta.write_text(json.dumps(obj,ensure_ascii=False,indent=2),encoding='utf8')
print('R11.27 PASS: comparison GUI table removed and no CSV population; adaptive window and mass controls; STEP unchanged')
